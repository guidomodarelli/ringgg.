import { build } from 'esbuild';
import { terminal } from './utils/terminal';

/** Source and output of the worker; `public/sw.js` is generated and ignored by Git. */
const SERVICE_WORKER = {
  entry: 'src/service-worker/service-worker.ts',
  tsconfig: 'src/service-worker/tsconfig.json',
  output: 'public/sw.js',
  target: 'es2020',
  banner: '/* Generated by scripts/build-service-worker.ts from src/service-worker. Do not edit. */',
};

const ui = terminal();
try {
  await ui.wait('Ringgg · Generando el service worker', () => build({
    entryPoints: [SERVICE_WORKER.entry],
    tsconfig: SERVICE_WORKER.tsconfig,
    outfile: SERVICE_WORKER.output,
    bundle: true,
    format: 'iife',
    target: SERVICE_WORKER.target,
    legalComments: 'none',
    banner: { js: SERVICE_WORKER.banner },
    logLevel: 'silent',
  }));
  ui.success(`OK · ${SERVICE_WORKER.output} generado desde ${SERVICE_WORKER.entry}.`);
} catch (error) {
  const location = (error as { errors?: Array<{ text: string; location?: { file: string; line: number } | null }> }).errors?.[0];
  ui.error(`ERROR · No se pudo generar el service worker${location?.location ? ` (${location.location.file}:${location.location.line}: ${location.text})` : ''}.`);
  process.exitCode = 1;
}
